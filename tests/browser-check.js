const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { spawn } = require('node:child_process');
async function main() {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'frame-browser-'));
  const server = spawn(process.execPath, ['server.js'], { cwd: path.join(__dirname, '..'), env: { ...process.env, PORT: '4318', FRAME_DATA_DIR: temporary }, windowsHide: true });
  let browser;
  try {
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); });
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:4318');
    await page.locator('#file-input').setInputFiles([path.join(__dirname, '../test-results/sample-with-audio.mp4'), path.join(__dirname, '../test-results/sample-silent.mp4')]);
    await page.waitForFunction(() => document.querySelectorAll('.media-card').length === 2);
    await page.waitForFunction(() => document.getElementById('video').readyState >= 2);
    assert.equal(await page.locator('.timeline-clip').count(), 2, 'Batch import adds every video');
    const timelineBounds = await page.locator('.timeline').boundingBox();
    assert.ok(timelineBounds.width > 1400, 'Timeline spans the desktop workspace');
    assert.equal(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight), false, 'Desktop workspace fits the viewport');
    const drag = async (from, to) => { await page.mouse.move(from.x, from.y); await page.mouse.down(); await page.mouse.move(to.x, to.y, { steps: 8 }); await page.mouse.up(); };
    const endHandle = await page.locator('.timeline-clip').first().locator('.trim-handle.end').boundingBox();
    await drag({ x: endHandle.x + 4, y: endHandle.y + 30 }, { x: endHandle.x - 26, y: endHandle.y + 30 });
    assert.equal(await page.locator('#trim-end').inputValue(), '2.50', 'Timeline right handle trims the end');
    await page.locator('#undo').click(); assert.equal(await page.locator('#trim-end').inputValue(), '3.00');
    await page.locator('#redo').click(); assert.equal(await page.locator('#trim-end').inputValue(), '2.50');
    await page.locator('#undo').click();
    const startHandle = await page.locator('.timeline-clip').first().locator('.trim-handle.start').boundingBox();
    await drag({ x: startHandle.x + 4, y: startHandle.y + 30 }, { x: startHandle.x + 34, y: startHandle.y + 30 });
    assert.equal(await page.locator('#trim-start').inputValue(), '0.50', 'Timeline left handle trims the start');
    await page.locator('#undo').click();
    const firstBounds = await page.locator('.timeline-clip').first().boundingBox();
    const secondBounds = await page.locator('.timeline-clip').nth(1).boundingBox();
    await drag({ x: firstBounds.x + firstBounds.width / 2, y: firstBounds.y + 30 }, { x: secondBounds.x + secondBounds.width + 15, y: secondBounds.y + 30 });
    assert.ok((await page.locator('.timeline-clip').first().getAttribute('aria-label')).includes('sample-silent'), 'Dragging reorders clips');
    await page.locator('#undo').click();
    await page.locator('#ruler').click({ position: { x: 60, y: 15 } });
    await page.waitForFunction(() => Math.abs(document.getElementById('video').currentTime - 1) < 0.05);
    const head = await page.locator('#timeline-playhead > span').boundingBox();
    await drag({ x: head.x + 6, y: head.y + 6 }, { x: head.x + 36, y: head.y + 6 });
    await page.waitForFunction(() => Math.abs(document.getElementById('video').currentTime - 1.5) < 0.05);
    await page.keyboard.press('Control+b'); assert.equal(await page.locator('.timeline-clip').count(), 3, 'Keyboard split uses draggable playhead');
    await page.locator('#undo').click();
    await page.keyboard.press('Control+d'); assert.equal(await page.locator('.timeline-clip').count(), 3, 'Keyboard duplicate');
    await page.locator('#undo').click();
    const mediaThumbnail = page.locator('.media-card').nth(1).locator('.media-thumbnail');
    const mediaTransfer = await page.evaluateHandle(() => new DataTransfer());
    await mediaThumbnail.dispatchEvent('dragstart', { dataTransfer: mediaTransfer });
    const rulerBox = await page.locator('#ruler').boundingBox();
    await page.locator('#timeline-scroll').dispatchEvent('drop', { dataTransfer: mediaTransfer, clientX: rulerBox.x + 5 });
    assert.equal(await page.locator('.timeline-clip').count(), 3, 'Media drag inserts a clip');
    assert.ok((await page.locator('.timeline-clip').first().getAttribute('aria-label')).includes('sample-silent'));
    await page.locator('#undo').click();
    const oldWidth = (await page.locator('.timeline-clip').first().boundingBox()).width;
    await page.locator('#zoom-in').click();
    assert.ok((await page.locator('.timeline-clip').first().boundingBox()).width > oldWidth);
    await page.locator('#timeline-zoom').fill('60');
    await page.locator('#media-search').fill('silent'); assert.equal(await page.locator('.media-card:visible').count(), 1);
    await page.locator('#media-search').fill('');
    await page.locator('#undo').click(); assert.equal(await page.locator('.timeline-clip').count(), 0, 'Batch addition undoes together');
    await page.locator('#timeline-join').click();
    await page.getByRole('checkbox', { name: 'Select sample-silent.mp4', exact: true }).check();
    await page.getByRole('checkbox', { name: 'Select sample-with-audio.mp4', exact: true }).check();
    await page.locator('#add-selected').click();
    assert.equal(await page.locator('.timeline-clip').count(), 2);
    assert.ok((await page.locator('.timeline-clip').first().getAttribute('aria-label')).includes('sample-silent.mp4'), 'Selection order sets join order');
    await page.locator('.timeline-clip').nth(1).click(); await page.locator('#timeline-earlier').click();
    assert.ok((await page.locator('.timeline-clip').first().getAttribute('aria-label')).includes('sample-with-audio.mp4'), 'Visible reorder controls change join order');
    await page.locator('#timeline-join').click(); await page.locator('#join-select-all').click(); await page.locator('#cancel-join').click();
    assert.equal(await page.locator('.timeline-clip').count(), 2, 'Cancel join leaves timeline unchanged');
    await page.locator('.timeline-clip').nth(1).click(); await page.locator('#remove').click();
    assert.equal(await page.locator('#trim-start').isDisabled(), false);
    await page.locator('#quick-crop').click();
    await page.locator('[data-crop-ratio="1:1"]').click();
    assert.equal(await page.locator('#crop-width').inputValue(), '360');
    const box = await page.locator('#crop-box').boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2, { steps: 4 }); await page.mouse.up();
    assert.ok(Number(await page.locator('#crop-x').inputValue()) > 140, 'Dragging moves crop selection');
    const handle = await page.locator('.crop-handle.se').boundingBox();
    await page.mouse.move(handle.x + 5, handle.y + 5); await page.mouse.down(); await page.mouse.move(handle.x - 30, handle.y - 30, { steps: 4 }); await page.mouse.up();
    assert.ok(Number(await page.locator('#crop-width').inputValue()) < 360, 'Dragging corner resizes crop');
    await page.locator('[data-crop-ratio="1:1"]').click();
    await page.locator('#apply-crop').click();
    assert.ok((await page.locator('#crop-summary').textContent()).includes('360 × 360'));
    await page.locator('#undo').click(); assert.ok((await page.locator('#crop-summary').textContent()).includes('Full frame'));
    await page.locator('#quick-crop').click(); await page.locator('[data-crop-ratio="9:16"]').click(); await page.locator('#cancel-crop').click();
    assert.ok((await page.locator('#crop-summary').textContent()).includes('Full frame'), 'Cancel preserves original');
    await page.locator('#quick-crop').click(); await page.locator('[data-crop-ratio="1:1"]').click(); await page.locator('#apply-crop').click();
    await page.locator('[data-edit-tool="trim"]').click();
    await page.locator('#trim-start').fill('0.25'); await page.locator('#trim-start').press('Tab');
    await page.locator('#trim-end').fill('2.75'); await page.locator('#trim-end').press('Tab');
    const editedCard = page.locator('.media-card').filter({ has: page.getByRole('button', { name: 'Edit sample-with-audio.mp4', exact: true }) });
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:02.5', 'Library duration matches trim');
    assert.equal(await editedCard.locator('.library-clip-range').textContent(), 'In 00:00.25 → Out 00:02.75');
    assert.ok((await editedCard.locator('.library-clip-state').textContent()).includes('Trimmed'));
    assert.ok((await editedCard.locator('.media-info').textContent()).includes('Original 00:03.0'), 'Source duration is retained');
    await page.locator('#trim-end').fill('0.1'); await page.locator('#trim-end').press('Tab');
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:02.5', 'Rejected trim leaves library state intact');
    await page.locator('#undo').click();
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:02.8', 'Undo updates library duration');
    await page.locator('#trim-end').fill('2.75'); await page.locator('#trim-end').press('Tab');
    await page.locator('[data-inspector-tab="adjust"]').click();
    await page.locator('[data-preset="vivid"]').click();
    await page.locator('[data-inspector-tab="audio"]').click();
    await page.locator('#speed').selectOption('7');
    assert.equal(await page.locator('#video').evaluate(video => video.playbackRate), 7, 'Preview supports 7x speed');
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:00.4', '7x duration updates the library');
    const fastProject = await page.evaluate(() => ({ version: 1, ...JSON.parse(localStorage.getItem('frame-project')) }));
    await page.locator('#project-input').setInputFiles({ name: 'fast.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fastProject)) });
    await page.waitForFunction(() => document.getElementById('speed').value === '7' && document.getElementById('video').playbackRate === 7);
    await page.locator('#speed').selectOption('1.5');
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:01.7', 'Library matches timeline duration after speed change');
    assert.ok((await editedCard.locator('.library-clip-state').textContent()).includes('1.5× speed'));
    await page.locator('#ruler').click({ position: { x: 48, y: 15 } });
    await page.waitForFunction(() => document.getElementById('video').currentTime > 1);
    await page.locator('#split').click();
    assert.equal(await page.locator('.timeline-clip').count(), 2);
    assert.equal(await editedCard.locator('.library-clip').count(), 2, 'Split clips have distinct library states');
    await editedCard.locator('.library-clip').first().click();
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:00.8');
    assert.equal(await page.locator('.timeline-clip').first().getAttribute('aria-pressed'), 'true');
    await page.locator('#remove').click();
    assert.equal(await editedCard.locator('.library-clip').count(), 1, 'Removed clip disappears from library edits');
    await page.locator('#undo').click();
    assert.equal(await editedCard.locator('.library-clip').count(), 2, 'Undo removal restores library edits');
    await editedCard.locator('.library-clip').nth(1).click();
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:00.9', 'Selected split clip controls library badge');
    await page.getByRole('button', { name: 'Add sample-silent.mp4 to timeline' }).click();
    assert.equal(await page.locator('.timeline-clip').count(), 3);
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '2 clips · 00:01.7', 'Unselected repeated source shows total edited duration');
    await page.locator('#timeline-earlier').click(); await page.locator('#undo').click();
    await page.locator('[data-inspector-tab="video"]').click();
    await page.locator('#aspect').selectOption('16:9');
    await page.locator('[data-inspector-tab="text"]').click();
    await page.locator('#title-text').fill('Made with Frame');
    const saved = page.waitForEvent('download'); await page.locator('#save-project').click(); const projectDownload = await saved;
    const projectPath = path.join(__dirname, '../test-results/browser-project.json'); await projectDownload.saveAs(projectPath);
    await page.locator('#new-project').click(); await page.locator('#confirm-new').click(); assert.equal(await page.locator('.timeline-clip').count(), 0);
    await page.locator('[data-inspector-tab="video"]').click();
    assert.equal(await page.locator('.media-card').count(), 0, 'New project has an empty media library');
    assert.equal(await page.locator('#trim-start').isDisabled(), true);
    await page.locator('#undo').click();
    assert.equal(await page.locator('.media-card').count(), 2, 'Undo new project restores its library');
    assert.equal(await page.locator('.timeline-clip').count(), 3);
    await page.locator('#redo').click();
    assert.equal(await page.locator('.media-card').count(), 0, 'Redo new project clears its library');
    await page.reload(); await page.waitForFunction(() => !!localStorage.getItem('frame-project'));
    assert.equal(await page.locator('.media-card').count(), 0, 'New library stays empty after refresh');
    await page.locator('#project-input').setInputFiles(projectPath);
    await page.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 3);
    assert.equal(await page.locator('.media-card').count(), 2, 'Saved project restores its media');
    await page.locator('.timeline-clip').first().click();
    await page.locator('#play-all').click();
    await page.waitForFunction(() => document.getElementById('play').getAttribute('aria-label') === 'Play timeline', { timeout: 15000 });
    assert.ok(Number(await page.locator('#scrubber').inputValue()) > 3.5, 'Playback traverses all three clips');
    await page.locator('.timeline-clip').first().click();
    await page.screenshot({ path: 'test-results/editor-desktop.png', fullPage: true });
    await page.reload(); await page.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 3);
    assert.equal(await editedCard.locator('.library-clip').count(), 2, 'Project open and reload restore library edits');
    assert.equal(await editedCard.locator('.duration-badge').textContent(), '00:00.8');
    assert.equal(await editedCard.locator('.library-clip-range').first().textContent(), 'In 00:00.25 → Out 00:01.45');
    assert.ok((await page.locator('#crop-summary').textContent()).includes('360 × 360'), 'Crop survives project save, open and reload');
    await page.locator('#open-export').click();
    assert.ok((await page.locator('#export-description').textContent()).includes('3 clips'));
    await page.locator('#resolution').selectOption('720'); await page.locator('#start-export').click();
    await page.locator('#download-export').waitFor({ state: 'visible', timeout: 90000 });
    const downloaded = page.waitForEvent('download'); await page.locator('#download-export').click(); await (await downloaded).saveAs('test-results/browser-export.mp4');
    await page.locator('#close-export').click();
    await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'test-results/editor-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile horizontal overflow');
    await page.locator('#quick-crop').click();
    await page.screenshot({ path: 'test-results/crop-mobile.png', fullPage: true });
    assert.equal(await page.locator('#crop-dialog').evaluate(el => el.scrollWidth > el.clientWidth), false, 'Crop dialog fits mobile width');
    await page.locator('#cancel-crop').click();
    const freshPage = await browser.newPage(); await freshPage.goto('http://127.0.0.1:4318');
    await freshPage.waitForFunction(() => !!localStorage.getItem('frame-project'));
    assert.equal(await freshPage.locator('.media-card').count(), 0, 'Fresh browser does not inherit other projects media');
    assert.equal(await freshPage.locator('.timeline-clip').count(), 0);
    await freshPage.locator('#file-input').setInputFiles(path.join(__dirname, '../test-results/sample-with-audio.mp4'));
    await freshPage.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 1);
    await freshPage.locator('#file-input').setInputFiles(path.join(__dirname, '../test-results/sample-silent.mp4'));
    await freshPage.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 2);
    assert.equal(await freshPage.locator('.timeline-clip').count(), 2, 'Later imports append to an existing timeline');
    assert.equal(await freshPage.locator('.media-card').count(), 2, 'Only current project imports appear');
    const legacyProject = JSON.parse(fs.readFileSync(projectPath, 'utf8')); delete legacyProject.mediaIds;
    await freshPage.locator('#project-input').setInputFiles({ name: 'legacy.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacyProject)) });
    await freshPage.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 3);
    assert.equal(await freshPage.locator('.media-card').count(), 2, 'Legacy saved project restores only its referenced sources');
    await freshPage.close();
    assert.deepEqual(errors, []);
    console.log('PASS: full-width timeline, drag trim/reorder, media insertion, ruler/playhead seeking, zoom, search, keyboard split/duplicate, undo/redo, inspector tabs, library synchronization, project persistence, MP4 export and responsive layout. No page errors.');
  } finally {
    await browser?.close(); server.kill(); await new Promise(resolve => server.once('close', resolve)); fs.rmSync(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
