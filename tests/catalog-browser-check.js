const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawn } = require('node:child_process');
async function main() {
  const root = path.join(__dirname, '..'), temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'frame-catalog-browser-'));
  const server = spawn(process.execPath, ['server.js'], { cwd: root, env: { ...process.env, PORT: '4320', FRAME_DATA_DIR: temporary }, windowsHide: true });
  let browser;
  try {
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Server exited: ${code}`))); });
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:4320');
    await page.locator('[data-workspace="audio"]').click();
    await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 11);
    await page.locator('#catalog-category').selectOption('Nature');
    await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 3);
    await page.locator('#catalog-category').selectOption('All');
    await page.locator('#catalog-search').fill('piano sad');
    await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 1);
    await page.getByRole('button', { name: 'Preview Touching Moments One - Pulse', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('catalog-preview').currentTime > 0.1);
    await page.getByRole('button', { name: 'Add Touching Moments One - Pulse from library', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.music-clip').length === 1);
    assert.equal(await page.locator('#catalog-preview').evaluate(audio => audio.paused), true, 'Adding stops the audition');
    assert.ok((await page.locator('.catalog-card').textContent()).includes('Credit required'));
    await page.locator('#file-input').setInputFiles(path.join(root, 'test-results/sample-with-audio.mp4'));
    await page.waitForFunction(() => document.querySelectorAll('.timeline-clip').length === 1);
    await page.locator('#open-export').click(); assert.equal(await page.locator('#export-credit-note').isVisible(), true);
    await page.locator('#start-export').click(); await page.locator('#download-export').waitFor({ state: 'visible', timeout: 90000 });
    assert.equal(await page.locator('#download-credits').isVisible(), true);
    const download = page.waitForEvent('download'); await page.locator('#download-credits').click();
    const creditsPath = path.join(root, 'test-results/catalog-export-credits.txt'); await (await download).saveAs(creditsPath);
    assert.match(fs.readFileSync(creditsPath, 'utf8'), /Kevin MacLeod/);
    await page.locator('#close-export').click();
    await page.locator('#catalog-provider').selectOption('epidemic');
    assert.equal(await page.locator('.catalog-card').count(), 0);
    assert.ok((await page.locator('#catalog-status').textContent()).includes('Connect'));
    await page.locator('#catalog-connect').click();
    await page.locator('#provider-save').click();
    await page.waitForFunction(() => document.getElementById('provider-result').textContent.includes('valid API key'));
    await page.locator('#close-audio-connections').click();
    await page.locator('#catalog-provider').selectOption('feed');
    assert.ok((await page.locator('#catalog-status').textContent()).includes('Partner onboarding'));
    assert.equal(await page.locator('.catalog-card').count(), 0, 'No pretend popular songs');
    await page.locator('#catalog-provider').selectOption('builtin'); await page.locator('#catalog-search').fill('nothing matches here');
    await page.waitForFunction(() => document.getElementById('catalog-status').textContent.includes('No matching'));
    await page.locator('#catalog-search').fill(''); await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 11);
    await page.screenshot({ path: path.join(root, 'test-results/catalog-desktop.png'), fullPage: true });
    await page.locator('#new-project').click(); await page.locator('#confirm-new').click();
    assert.equal(await page.locator('.music-card').count(), 0, 'Project audio clears on New');
    assert.equal(await page.locator('.catalog-card').count(), 11, 'Shared discovery catalog remains available');
    await page.locator('#catalog-search').fill('piano sad'); await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 1);
    await page.getByRole('button', { name: 'Add Touching Moments One - Pulse from library', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.music-clip').length === 1);
    await page.locator('[data-audio-view="project"]').click(); assert.equal(await page.locator('.music-card').count(), 1);
    await page.reload(); await page.waitForFunction(() => document.querySelectorAll('.music-clip').length === 1);
    await page.locator('[data-workspace="audio"]').click();
    await page.locator('#catalog-search').fill('carefree'); await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 1);
    await page.context().setOffline(true);
    await page.getByRole('button', { name: 'Preview Carefree', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('toast').textContent.includes('fetch') || document.getElementById('toast').textContent.includes('network'));
    await page.context().setOffline(false);
    await page.locator('#catalog-search').fill(''); await page.waitForFunction(() => document.querySelectorAll('.catalog-card').length === 11);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Add Touching Moments One - Pulse from library', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.music-clip').length === 2);
    const addBounds = await page.getByRole('button', { name: 'Add Touching Moments One - Pulse from library', exact: true }).boundingBox();
    const listBounds = await page.locator('#catalog-results').boundingBox();
    assert.ok(addBounds.y + addBounds.height <= listBounds.y + listBounds.height, 'Mobile Add button is fully visible within its card list');
    await page.screenshot({ path: path.join(root, 'test-results/catalog-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('PASS: real catalog, search/categories, audible previews, add/export/credits, provider setup and gating, new-project isolation, persisted library audio, network errors and mobile layout.');
  } finally {
    await browser?.close(); server.kill(); await new Promise(resolve => server.once('close', resolve)); fs.rmSync(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
